import { apca, build, difference, inkOn, ratio, STEP_MIN, tightest } from './build.mjs'

/* Первые два порога — WCAG 2.2 (SC 1.4.3 и 1.4.11). Третий наш: разбор в
   palette.md, «Фирменный цвет совпал с красным». Четвёртый и пятый —
   обещание САМОГО эталона, снятое с его файлов: 11-я ступень даёт Lc 60 на
   2-й той же шкалы, 12-я — Lc 90. Это единственная метрика, в которой эталон
   вообще что-то обещает (И191). */
export const NEED = { text: 4.5, control: 3, brandApart: 25, mutedLc: 60, mainLc: 90 }

/** Двадцать правил для одного набора в одной теме.
 *  Возвращает только НАХОДКИ: пустой список — набор в норме. */
export function audit(paints, mode) {
  const b = build(paints, mode)
  const { n, a, e } = b

  const found = []
  const want = (rule, got, need) => {
    if (got < need) found.push({ rule, got: Number(got.toFixed(2)), need })
  }

  /* ── читается ли написанное: WCAG, ворота ── */
  want('основной текст на карточке', ratio(n[11], n[1]), NEED.text)
  want('приглушённый текст на карточке', ratio(n[10], n[1]), NEED.text)
  want('цена фирменным на карточке', ratio(a[10], n[1]), NEED.text)
  want('знак на кнопке покупки', ratio(inkOn(a[8]), a[8]), NEED.text)
  want('кольцо фокуса на листе', ratio(b.ring, n[0]), NEED.control)
  want('граница органа управления', ratio(b.bound, n[1]), NEED.control)
  want('фирменный отличим от красного', difference(a[8], e[8]), NEED.brandApart)

  /* Красный — такая же шкала, как марка: на нём стоит «нет в наличии» и
     текст ошибки у поля, и до 20.09.2026 его не мерил никто (И190). */
  want('текст ошибки на карточке', ratio(e[10], n[1]), NEED.text)
  want('знак на заливке ошибки', ratio(inkOn(e[8]), e[8]), NEED.text)

  /* ── обещание эталона: APCA (И191) ──
     На этих же парах в тёмной теме WCAG показывает 6.2–8.4 при норме 4.5 —
     «с запасом», пока APCA держится на 55.8. */
  want('приглушённый текст держит обещание эталона', apca(n[10], n[1]), NEED.mutedLc)
  want('основной текст держит обещание эталона', apca(n[11], n[1]), NEED.mainLc)
  want('цена фирменным держит обещание эталона', apca(a[10], n[1]), NEED.mutedLc)
  want('текст ошибки держит обещание эталона', apca(e[10], n[1]), NEED.mutedLc)

  /* ── ход лестницы (И189) ──
     Две ступени с разной работой в одной краске — это контрол без ответа
     или цена, неотличимая от текста. */
  want('нейтральная лестница не схлопывается', tightest(n, mode), STEP_MIN)
  want('фирменная лестница не схлопывается', tightest(a, mode), STEP_MIN)
  want('красная лестница не схлопывается', tightest(e, mode), STEP_MIN)

  /* ── ответ кнопки на руку ──
     Слишком большой сдвиг — та же беда, что и нулевой: обвал янтаря заказчик
     назвал «слишком большое изменение оттенка» раньше, чем это дали числа. */
  want('наведение кнопки заметно', b.hover, 2)
  want('нажатие кнопки заметно', b.pushedBy, 4)
  if (b.hover > 8) found.push({ rule: 'наведение кнопки не обвал', got: Number(b.hover.toFixed(2)), need: 8 })
  if (b.pushedBy > 16) found.push({ rule: 'нажатие кнопки не обвал', got: Number(b.pushedBy.toFixed(2)), need: 16 })

  return found
}

/*
 * Правила «текст на худшей поверхности» и «тон шкалы не плывёт» здесь НЕТ, и
 * это замер, а не недосмотр. Оба стоят в чек-листе исследования, и обоих не
 * держит сам эталон:
 *
 *   · приглушённый текст на НАЖАТОМ контроле — в светлой теме 25 шкал из 31
 *     дают там ниже WCAG 4.5 (худшая `orange` — 3.19), в тёмной ниже Lc 60
 *     стоят 27 из 31. Значит эталон не ставит приглушённый текст на контрол
 *     вовсе: обещание дано на второй ступени и только на ней. Это граница
 *     РОЛИ, а не порог контраста;
 *   · |Δh| ступеней 3–11 к краске ≤ 10° — у эталона до 38.9° (`sand`,
 *     ступень 3; среди цветных `orange` 34.1°), а наш худший набор 24.1°.
 *
 * Правило, которого сам эталон не держит, — чужое мнение, а не опыт.
 * Разбор с числами — palette.md, «Два правила исследования, которые
 * правилами не стали».
 */
