/*
 * Реестр швов раскладки — слой 8.
 *
 * Шов — это РЕШЕНИЕ, а не число: ширина окна, на которой раскладка целой
 * страницы меняет смысл (колонка становится строкой, шапка — карточкой,
 * появляется док). Пока решения не записаны, каждая сессия ставит своё:
 * cbdshop.bg к 31.08.2026 набрал тринадцать разных ширин в медиазапросах,
 * пять из них не объяснял никто (`packages/ui/src/tokens/seams.ts`); cbdin
 * держал три разрешённых числа списком — без имени и причины, и две из трёх
 * (1080, 560) в CSS набора не читал никто, кроме концов рамп.
 *
 * Что здесь записано и чего нельзя прочитать из CSS: ПОЧЕМУ ширина именно
 * такая и ЧТО на ней меняется. Числа остаются в CSS — медиазапрос не умеет
 * `var()`, а подменять его сборкой значит завести второй язык раскладки
 * рядом с первым. Поэтому реестр не заменяет CSS, а не даёт появиться шву,
 * о котором никто не договаривался, — и в обе стороны:
 *   · ширина в `@media`, которой нет в реестре, — семья `breakpoint`;
 *   · запись, которую не читает ни один медиазапрос и ни один конец рампы,
 *     — семья `deadSeam`.
 * Так у Carbon (таблица: шов → колонки → поле; «test designs and code at
 * each of these standard breakpoints»), у M3 (пять классов окна, не больше:
 * «Design for breakpoints instead of specific devices»), у web.dev («choose
 * your breakpoints based on your content rather than popular device sizes»).
 * Швов не больше `LAYOUT.seams`; каждый — с именем и причиной не короче
 * сорока знаков (сторож cbdshop требовал того же).
 *
 * Свой реестр проект пишет в `kit.config.json` ключом `seams` тем же видом;
 * умолчания ниже — набора. Ширина ±1 — тот же шов: пара
 * `(min-width: 820px)` / `(max-width: 819px)` пишется об одном решении.
 */

