/** Ширины окна из медиазапросов: `@media (max-width: 820px)` → 820.
 *  `@container` швом не считается: узел меряет свою коробку, а не окно. */
export const seamsIn = (css) => {
  const found = new Set()
  for (const m of css.matchAll(/@media[^{]*?\((?:max|min)-width\s*:\s*(\d+)px/g)) found.add(Number(m[1]))
  return [...found].sort((a, b) => b - a)
}

/** Тот же шов ±1: `859` и `861` — это 860, взятое «строго ниже» и «строго выше». */
export const sameSeam = (a, b) => Math.abs(a - b) <= 1

/** Форма реестра: имя, причина не короче сорока знаков, одна запись на
 *  ширину, не больше порога. Ошибки формы — не долг, а неверный конфиг. */
export const auditSeamsShape = (seams, max) => {
  const bad = []
  if (!Array.isArray(seams)) return ['реестр швов — список записей { at, name, turns, why }']
  const seen = new Set()
  for (const s of seams) {
    if (!s || typeof s.at !== 'number') { bad.push(`шов без ширины: ${JSON.stringify(s)}`); continue }
    if (seen.has(s.at)) bad.push(`шов ${s.at} записан дважды`)
    seen.add(s.at)
    if (!s.name) bad.push(`шов ${s.at} без имени`)
    if (!s.turns) bad.push(`шов ${s.at}: не сказано, что на нём меняется (turns)`)
    if (!s.why || s.why.length < 40) bad.push(`шов ${s.at}: причина короче сорока знаков — «так вышло» причиной не считается`)
  }
  if (typeof max === 'number' && seams.length > max) bad.push(`швов ${seams.length}, разрешено не больше ${max} (LAYOUT.seams)`)
  return bad
}

/**
 * Реестр против CSS, в сторону «запись без читателя». Читатель шва —
 * медиазапрос по ширине (±1) в любом файле стилей ИЛИ конец рампы набора
 * шкал (`ширины` в styles/scale.json): концы рамп — тоже решения о ширине.
 * `sheets` — `{ rel, css }`; `rampEnds` — числа.
 */
export const deadSeams = (seams, sheets, rampEnds = []) => {
  const read = new Set()
  for (const { css } of sheets) for (const w of seamsIn(css)) read.add(w)
  for (const w of rampEnds) read.add(Number(w))
  const out = []
  for (const s of seams) {
    if ([...read].some((w) => sameSeam(w, s.at))) continue
    out.push(`шов ${s.at} «${s.name}» не читает ни один медиазапрос и ни один конец рампы — запись без решения в CSS`)
  }
  return out
}

/** Ширины свипа: сетка шагом `step` от первой до последней ширины, плюс
 *  каждый шов и пиксель над ним (ступенька живёт на 820 / 821), плюс
 *  сложенные внутренние экраны. Ломается всегда именно там. */
export const sweepWidths = (layout, seams) => {
  const [from, to] = layout.sweep
  const set = new Set()
  for (let w = from; w <= to; w += layout.step) set.add(w)
  for (const s of seams) { set.add(s.at); set.add(s.at + 1) }
  for (const w of layout.extra ?? []) set.add(w)
  return [...set].filter((w) => w >= from && w <= to).sort((a, b) => a - b)
}
