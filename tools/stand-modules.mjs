/*
 * CSS-модуль на стенде без сборщика (И335).
 *
 * `composes` — единственное, чем модуль отличается от простого CSS: сборщик
 * вешает взятый класс на тот же элемент. Снять строку мало — пропадает всё,
 * что класс берёт. Так с 24.09.2026 (И273, `.btn{composes:press}`) стенды
 * показывали тихую кнопку голым словом: заливка, вуаль и ответ на руку живут
 * в `.press`, а до кнопки он не доезжал. Взятые классы ставились в разметку
 * рукой (`box pick`) — и первый же новый `composes` рука не заметила.
 *
 * Поэтому стенд делает то же, что сборщик: строку снимает из CSS, а взятые
 * классы ставит в разметку сам, по тексту модулей.
 */

/** CSS модуля без `composes`: вне сборщика это не объявление, а мусор. */
export const plainCss = (css) => css.replace(/composes\s*:[^;}]*;?/g, '')

/** Класс → классы, которые он берёт (`from '…'` — из соседнего модуля;
 *  на стенде тот вставлен целиком, и имя то же). */
export function takenBy(...sheets) {
  const map = {}
  for (const css of sheets) {
    for (const m of css.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/\.([\w-]+)\s*\{[^{}]*?composes\s*:\s*([^;}]+)/g)) {
      map[m[1]] = [...(map[m[1]] ?? []), ...m[2].replace(/\bfrom\s+(['"])[^'"]*\1/g, '').trim().split(/\s+/).filter(Boolean)]
    }
  }
  return map
}

/** Разметка с взятыми классами: каждый класс тянет за собой всё, что берёт,
 *  и то, что берут взятые. Взятое стоит перед берущим, как у сборщика. */
export function withTaken(html, map) {
  const all = (c, seen = new Set()) => (seen.has(c) ? [] : (seen.add(c), [...(map[c] ?? []).flatMap((t) => all(t, seen)), c]))
  return html.replace(/class="([^"]*)"/g, (_, list) => `class="${[...new Set(list.split(/\s+/).filter(Boolean).flatMap((c) => all(c)))].join(' ')}"`)
}
