const plain = (s) => String(s ?? '').toLowerCase().replace(/ё/g, 'е')
const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const DESIGN_RX = DESIGN.words.map((w) => [w, new RegExp(`(?<![\\p{L}\\p{N}_])${escape(plain(w))}`, 'u')])

/** Слова про вид витрины → первый найденный корень, иначе null. */
export function designWord(text) {
  const t = plain(text)
  return DESIGN_RX.find(([, rx]) => rx.test(t))?.[0] ?? null
}

/** Подсказка о порядке — две строки, одни и те же у хука и у разбора фразы. */
export const designHint = (word) => [
  `Слова заказчика — про вид («${word}…»). Дизайн делается дизайнерскими скиллами, по порядку: ${DESIGN.order.join(' → ')}.`,
  `Разбор готовой страницы — ${DESIGN.audit}; рядом — ${DESIGN.alongside}. Правила набора (роли, примитивы, швы, ни одного числа на месте) старше умолчаний скилла; итог — заказчику отрисованным (${DESIGN.rule}).`,
]

/* ── печать ───────────────────────────────────────────────────────────── */

const isCli = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (isCli) {
  const asked = process.argv.slice(2).filter((a) => !a.startsWith('--')).join(' ')

  if (asked) {
    const r = match(asked)
    const look = designWord(asked)
    if (look) console.log(`\n${designHint(look).join('\n')}`)
    if (!r.checks.length) {
      console.log(`\nПод «${asked}» проверки не подобрались. Весь список: node tools/checks.mjs`)
    } else if (r.kind === 'all' || r.kind === 'final') {
      console.log(`\nПод «${asked}» — вся цепочка${r.kind === 'final' ? ' сдачи' : ''}: npm run check:all${r.kind === 'final' ? ' -- --final' : ''}`)
      console.log(`Почему: ${r.why.join(', ')}`)
    } else {
      console.log(`\nПод «${asked}» запускается:`)
      for (const cmd of r.checks) console.log(`  npm run ${cmd.replace(/^test$/, 'test')}   — ${nameOf(cmd)}`)
      console.log(`\nПочему: ${r.why.join('; ')}`)
    }
    process.exit(0)
  }

  /* Ширина первой колонки считается, а не назначается: имя проверки
     когда-нибудь станет длиннее, и таблица не должна разъезжаться. */
  const w = Math.max(...CHECKS.map((c) => c.name.length))
  console.log('\nЧто проверяется — и как это назвать словами\n')
  for (const c of CHECKS) {
    const mark = c.needs === 'браузер' ? ' (нужен поднятый сайт)' : c.needs === 'сборка' ? ' (нужна сборка)' : ''
    console.log(`  ${c.name.padEnd(w)}  ${c.watches}${mark}`)
    console.log(`  ${' '.repeat(w)}  npm run ${c.cmd}`)
  }
  console.log(`
  всё сразу${' '.repeat(Math.max(0, w - 9))}  всё, что нужно на сегодняшнем этапе, по порядку и с вердиктом
  ${' '.repeat(w)}  npm run check:all   (к сдаче: npm run check:all -- --final)

Дизайн — не проверка, а порядок скиллами: ${DESIGN.order.join(' → ')};
разбор готовой страницы — ${DESIGN.audit} (${DESIGN.rule}).

Заказчику команды не нужны: он говорит словами — «шрифты поехали», «проверь
сайт», «готово ли к сдаче», — а какие проверки под этими словами, разбирает
node tools/checks.mjs "<его слова>" и хук на каждый ввод (tools/hook-on-prompt.mjs).
`)
  try {
    const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'))
    const missing = CHECKS.filter((c) => !pkg.scripts?.[c.cmd])
    if (missing.length) {
      console.log(`⚠ в package.json нет команд: ${missing.map((c) => c.cmd).join(', ')}`)
    }
  } catch { /* нет package.json — не о чем говорить */ }
}
