/** Просьба проверить вообще, без предмета. */
const VERBS = ['проверь', 'проверить', 'провер', 'посмотри', 'глянь', 'прогон', 'протест']

const norm = (s) => s.toLowerCase().replace(/ё/g, 'ё').replace(/[^\wа-яё\s:-]/gi, ' ')

/**
 * Что запускать под эти слова.
 *
 * Возвращает `{ kind, checks, why }`, где kind — 'all' (гнать всю цепочку
 * этапа), 'final' (цепочку сдачи) или 'some' (названные проверки).
 * Пустой список значит «слова не про проверку» — и тогда ничего не
 * печатается: подсказка на каждую реплику была бы шумом.
 */
export function match(text) {
  const t = norm(String(text ?? ''))
  if (!t.trim()) return { kind: 'none', checks: [], why: [] }

  if (FINAL_WORDS.some((w) => t.includes(w))) {
    return { kind: 'final', checks: CHECKS.map((c) => c.cmd), why: ['спрашивают про сдачу'] }
  }
  if (ALL_WORDS.some((w) => t.includes(w))) {
    return { kind: 'all', checks: CHECKS.map((c) => c.cmd), why: ['просят проверить целиком'] }
  }

  const hit = [], why = []
  for (const c of CHECKS) {
    const word = c.words.find((w) => t.includes(w))
    if (word) { hit.push(c.cmd); why.push(`«${word}…» → ${c.name}`) }
  }
  if (hit.length) return { kind: 'some', checks: hit, why }

  /* Сказали «проверь», не назвав что. Это не «ничего не запускать», а
     «запустить всё»: переспрашивать «что именно проверить?» — значит
     перекладывать на заказчика работу, которую он уже поручил. */
  if (VERBS.some((w) => t.includes(w))) {
    return { kind: 'all', checks: CHECKS.map((c) => c.cmd), why: ['просят проверить, предмет не назван'] }
  }
  return { kind: 'none', checks: [], why: [] }
}

