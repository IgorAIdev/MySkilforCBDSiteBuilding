import type { Image } from './source/contract.ts'

/** Место снимка на витрине — сколько ширины он там займёт. У ленивого
 *  снимка первым стоит `auto`: браузер берёт ширину из раскладки сам, и
 *  место меряется коробкой, а не окном; дальше — запас для браузера без
 *  `auto`. У снимка первого экрана `auto` не ставится: Chromium тогда
 *  отбрасывает весь `sizes` и считает снимок во всю ширину окна (замер
 *  25.09.2026: 140-пиксельный снимок в карточке 319 пикселей грузился как
 *  1440). Швы — из реестра (tools/seams.mjs). */
export const SIZES = {
  /** Карточка полки и плитка полки: четверть ряда на широком, половина на телефоне. */
  shelf: '(min-width: 820px) 25vw, 50vw',
  /** Кадр карты товара: половина окна на широком, всё окно на телефоне. */
  stage: '(min-width: 820px) 50vw, 100vw',
  /** Снимок во всю коробку страницы: герой, пауза, слово магазина. */
  wide: '100vw',
  /** Миниатюра: строка корзины и заказа, меню полок, ряд под кадром, карточка на снимке, снимок в строке. */
  thumb: '160px',
} as const

export type Place = keyof typeof SIZES

/** Атрибуты `<img>` снимка: адрес, ширины от сервера снимков (если источник
 *  их дал) с местом, размеры, по которым место занято до загрузки, и ленивая
 *  загрузка. Ленивость и место решаются здесь вместе: `auto` в месте
 *  действует только у ленивого снимка. Один на витрину: снимок, нарисованный
 *  мимо, отдаёт одну ширину на все места (`check:craft`, семья `weight`). */
export const shot = (image: Image, place: Place, lazy = false) => ({
  src: image.src, width: image.width, height: image.height,
  ...(lazy ? { loading: 'lazy' as const } : {}),
  ...(image.srcset ? { srcSet: image.srcset, sizes: lazy ? `auto, ${SIZES[place]}` : SIZES[place] } : {}),
})
