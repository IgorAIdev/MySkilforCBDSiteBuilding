import type { Lang } from './locale.ts'

/* Запись числа — одна на витрину и по языку страницы (И347): цена,
   строка фактов карточки, значения грани «Сила», протокол партии и плашка
   скидки пишут число здесь, компонент получает готовую строку.

   Дефект, которым это куплено (24.09.2026): число писалось тегом рынка
   `intlLocale` (`en-RO`), и `Intl` у него половинчатый — дробь по-румынски,
   цена по-английски. Английская страница печатала «2,5 %» и «10,2 %» рядом с
   «€1,234.50»; значения грани образца были набраны рукой, по-английски тоже
   с запятой. Язык страницы решает, как пишется число; регион рынка решает
   валюту, порядок даты и имена регионов (`intlLocale`) — не цифры. */

/** Неразрывный пробел: число не отрывается от своей единицы («30 / % forte»
 *  рвалось на телефоне посередине). Тот же знак `Intl` ставит между суммой
 *  и валютой. */
export const BIND = ' '

/** Тег `Intl` для чисел — язык страницы, без региона рынка: en — «2.5»,
 *  «12,500»; ro — «2,5», «12.500»; hu — «2,5», «12 500». */
export const numberLocale = (lang: Lang): string => lang

/** Число до `digits` знаков после запятой. Четыре знака без разрядки —
 *  «1000 mg», как на этикетке; разрядка с пяти. */
export const num = (lang: Lang, value: number, digits = 1): string =>
  new Intl.NumberFormat(numberLocale(lang), { maximumFractionDigits: digits, useGrouping: 'min2' }).format(value)

/** Процент — числом языка страницы и знаком через неразрывный пробел:
 *  «2.5 %», «2,5 %». `value` — проценты (2.5), а не доля. Одна запись на
 *  строку фактов, грань, протокол и скидку: знак, который в одном месте
 *  стоит вплотную, а в соседнем через пробел, читается двумя разными. */
export const percent = (lang: Lang, value: number, digits = 1): string => `${num(lang, value, digits)}${BIND}%`
